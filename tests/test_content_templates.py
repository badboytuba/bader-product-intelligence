    def test_structured_generation_is_read_only_preserves_name_and_fixed_layout(self):
        self.child_category.bpi_content_template_id = self.instrumental
        before = self._snapshot()
        result, prompt = self._generate(self._structured_response(name="No renombrar"))
        tree = html.fragment_fromstring(result["technicalDescriptionHtml"], create_parent="div")
        self.assertEqual(tree.xpath("./h3/text()"), ["Descripción General", "Especificaciones Técnicas"])
        self.assertEqual(len(tree.xpath("./h3[1]/following-sibling::p[following-sibling::h3]")), 2)
        self.assertFalse(tree.xpath(".//h1|.//h2|.//script|.//style"))
        self.assertEqual(result["name"], self.product.name)
        self.assertEqual(result["contentTemplates"]["effective"]["id"], self.instrumental.id)
        self.assertIn("45-70", prompt)
        self.assertNotIn("350-650", prompt)
        self.assertNotIn("OLD_AI_NOT_TECHNICAL_EVIDENCE", prompt)
        self.assertNotIn("OLD_TECH_NOT_CONFIRMED_EVIDENCE", prompt)
        self.assertEqual(self._snapshot(), before)

