    def setUp(self):
        super().setUp()
        transport = patch.object(
            type(self.service), "_openai_request",
            side_effect=AssertionError("Content-template tests must not call an external provider"),
        )
        self.blocked_transport = transport.start()
        self.addCleanup(transport.stop)
        # TransactionCase fixtures are deliberately uncommitted and cannot be
        # read through the production second-cursor visibility check. Preserve
        # the guard itself while resolving fixture metadata in this transaction.
        # Real cross-transaction freshness is certified separately in QAS.
        def fixture_context(service, product_id, template_id=CONTENT_TEMPLATE_UNSET):
            return service.content_template_context(service._meli_product(product_id), template_id=template_id)

        freshness = patch.object(type(self.service), "_content_template_fresh_context", fixture_context)
        freshness.start()
        self.addCleanup(freshness.stop)

    def _new_template(self, **values):
        defaults = {
            "name": "BPI Template Alternative",
            "short_instructions": "Resumen con datos confirmados.",
            "long_instructions": "Ficha técnica sin inventar características.",
            "format": "free",
        }
        defaults.update(values)
        return self.templates.create(defaults)

    def _snapshot(self):
        return self.product.read([
            "name", "categ_id", "public_categ_ids", "bpi_content_template_id",
            "description_sale", "bpi_ai_generated_description", "bpi_technical_description",
            "website_meta_title", "bpi_geo_title", "bpi_faq_ids", "website_published", "write_date",
        ])[0]

    def _structured_response(self, **values):
        response = {
            "description": "Resumen comercial de la espátula para revisión profesional.",
            "generalParagraphs": [
                "La espátula está destinada al trabajo con composite según su identificación guardada.",
                "Los materiales y las condiciones de mantenimiento requieren datos técnicos confirmados.",
            ],
            "specificationIds": [],
        }
        response.update(values)
        return response

    def _generate(self, response, **kwargs):
        with patch.object(type(self.service), "_openai_json", return_value=response) as provider:
            result = self.service.generate_content(self.product, **kwargs)
        provider.assert_called_once()
        return result, provider.call_args.args[0]

    def test_seed_contract_and_noupdate_preserve_operator_edits(self):
        self.assertEqual(self.general.format, "free")
        self.assertEqual((self.general.short_min_words, self.general.short_max_words), (45, 70))
        self.assertEqual((self.general.long_min_words, self.general.long_max_words), (350, 650))
        self.assertEqual(self.instrumental.format, "two_sections")
        self.assertEqual((self.instrumental.short_min_words, self.instrumental.short_max_words), (45, 70))
        self.assertFalse(self.instrumental.long_min_words)
        self.assertFalse(self.instrumental.long_max_words)
        for name in ("content_template_general", "content_template_instrumental"):
            data = self.env["ir.model.data"].search([
                ("module", "=", "bader_product_intelligence"), ("name", "=", name),
            ])
            self.assertEqual(len(data), 1)
            self.assertTrue(data.noupdate)

    def test_general_fallback_ignores_matching_public_category_name(self):
        context = self.service.content_template_context(self.product)
        self.assertEqual(context["effective"]["id"], self.general.id)
        self.assertEqual(context["source"]["kind"], "general")
        self.assertFalse(context["selectionId"])
        self.assertEqual(context["internalCategory"]["id"], self.leaf_category.id)

    def test_direct_internal_category_and_nearest_ancestor_are_deterministic(self):
        alternative = self._new_template()
        self.root_category.bpi_content_template_id = self.general
        self.child_category.bpi_content_template_id = self.instrumental
        context = self.service.content_template_context(self.product)
        self.assertEqual(context["effective"]["id"], self.instrumental.id)
        self.assertEqual(context["source"]["kind"], "ancestor")
        self.assertEqual(context["source"]["categoryId"], self.child_category.id)
        self.leaf_category.bpi_content_template_id = alternative
        direct = self.service.content_template_context(self.product)
        self.assertEqual(direct["effective"]["id"], alternative.id)
        self.assertEqual(direct["source"]["kind"], "category")
        self.assertEqual(direct["source"]["categoryId"], self.leaf_category.id)

    def test_future_descendant_inherits_without_product_specific_setup(self):
        self.child_category.bpi_content_template_id = self.instrumental
        future_category = self.env["product.category"].create({
            "name": "Nuevo instrumental", "parent_id": self.leaf_category.id,
        })
        product = self.env["product.template"].create({
            "name": "Producto futuro", "categ_id": future_category.id,
        })
        context = self.service.content_template_context(product)
        self.assertEqual(context["effective"]["id"], self.instrumental.id)
        self.assertFalse(product.bpi_content_template_id)

    def test_one_model_serves_multiple_roots_without_name_matching(self):
        other_root = self.env["product.category"].create({
            "name": "Un nombre diferente", "bpi_content_template_id": self.instrumental.id,
        })
        self.child_category.bpi_content_template_id = self.instrumental
        other = self.env["product.template"].create({"name": "Otra ficha", "categ_id": other_root.id})
        self.assertEqual(self.service.content_template_context(other)["effective"]["id"], self.instrumental.id)
        self.assertEqual(self.service.content_template_context(self.product)["effective"]["id"], self.instrumental.id)
        self.assertIn(other_root, self.instrumental.category_ids)
        self.assertIn(self.child_category, self.instrumental.category_ids)

    def test_saved_manual_override_wins_and_explicit_auto_is_read_only(self):
        self.child_category.bpi_content_template_id = self.instrumental
        self.product.bpi_content_template_id = self.general
        before = self._snapshot()
        saved = self.service.content_template_context(self.product)
        self.assertEqual(saved["effective"]["id"], self.general.id)
        self.assertEqual(saved["selectionId"], self.general.id)
        self.assertEqual(saved["source"]["kind"], "manual")
        for automatic in (False, None):
            context = self.service.content_template_context(self.product, template_id=automatic)
            self.assertEqual(context["effective"]["id"], self.instrumental.id)
            self.assertFalse(context["selectionId"])
        self.assertEqual(self._snapshot(), before)

    def test_detail_exposes_internal_category_without_redefining_shop_category(self):
        self.child_category.bpi_content_template_id = self.instrumental
        before = self._snapshot()
        with patch.object(type(self.service), "_openai_json") as provider:
            payload = self.product.bpi_build_payload()
