    def test_revision_changes_on_edit_and_context_exposes_instructions(self):
        template = self._new_template()
        old_revision = template.revision
        template.write({"short_instructions": "Instrucción corta revisada."})
        self.assertGreater(template.revision, old_revision)
        context = self.service.content_template_context(self.product, template_id=template.id)
        self.assertEqual(context["effective"]["revision"], template.revision)
        self.assertEqual(context["effective"]["shortInstructions"], "Instrucción corta revisada.")
        self.assertEqual(context["effective"]["longInstructions"], template.long_instructions)

    def test_unreferenced_model_can_be_duplicated_archived_and_deleted(self):
        template = self._new_template()
        duplicate = template.copy({"name": "Modelo duplicado"})
        self.assertNotEqual(template, duplicate)
        self.assertEqual(duplicate.short_instructions, template.short_instructions)
        self.assertEqual(duplicate.long_instructions, template.long_instructions)
        self.assertFalse(duplicate.category_ids)
        template.active = False
        context = self.service.content_template_context(self.product)
        self.assertNotIn(template.id, [item["id"] for item in context["options"]])
        with self.assertRaises(ValidationError):
            self.service.content_template_context(self.product, template_id=template.id)
        template.unlink()
        self.assertFalse(template.exists())

    def test_general_model_cannot_be_archived_or_deleted(self):
        for operation in (lambda: self.general.write({"active": False}), self.general.unlink):
            with self.assertRaises(UserError):
                operation()
        self.assertTrue(self.general.exists())
        self.assertTrue(self.general.active)

    def test_category_referenced_model_requires_explicit_replacement(self):
        template = self._new_template()
        self.child_category.bpi_content_template_id = template
        for operation in (lambda: template.write({"active": False}), template.unlink):
            with self.assertRaises(UserError):
                operation()
        self.child_category.bpi_content_template_id = self.instrumental
        template.active = False
        self.assertFalse(template.active)

    def test_archived_product_override_still_protects_model_lifecycle(self):
        template = self._new_template()
        self.product.write({"bpi_content_template_id": template.id, "active": False})
        for operation in (lambda: template.write({"active": False}), template.unlink):
            with self.assertRaises(UserError):
                operation()
        self.product.bpi_content_template_id = False
        template.unlink()
        self.assertFalse(template.exists())

    def test_save_content_patch_preserves_override_until_explicit_auto(self):
        self.child_category.bpi_content_template_id = self.instrumental
        payload = self.service.save_content(self.product, {
            "templateId": self.general.id,
            "description": "<p>Resumen guardado explícitamente.</p>",
        })
        self.assertEqual(self.product.bpi_content_template_id, self.general)
        self.assertEqual(payload["contentTemplates"]["selectionId"], self.general.id)
        self.service.save_content(self.product, {"tone": "profesional"})
        self.assertEqual(self.product.bpi_content_template_id, self.general)
        payload = self.service.save_content(self.product, {"templateId": False})
        self.assertFalse(self.product.bpi_content_template_id)
        self.assertEqual(payload["contentTemplates"]["effective"]["id"], self.instrumental.id)
        self.assertIn("Resumen guardado explícitamente", self.product.bpi_ai_generated_description)

    def test_save_content_null_clears_override_without_changing_descriptions(self):
        self.product.bpi_content_template_id = self.instrumental
        before = self._snapshot()
        self.service.save_content(self.product, {"templateId": None})
        after = self._snapshot()
        self.assertFalse(after["bpi_content_template_id"])
        for field in before:
            if field not in {"bpi_content_template_id", "write_date"}:
                self.assertEqual(after[field], before[field], field)

